use std::io::Cursor;
use std::pin::Pin;
use std::sync::Arc;

use async_trait::async_trait;
use empath_common::context::Context;
use tokio::io::AsyncRead;

use crate::types::SpooledMessageId;

pub type MessageStream = Pin<Box<dyn AsyncRead + Send + Unpin>>;

#[derive(Debug, Clone, Copy, Default)]
pub struct SpoolScanCursor {
    pub offset: u64,
}

#[derive(Debug, Clone, Copy)]
pub enum SpoolScanMode {
    Full,
    Delta,
}

/// Minimal metadata view for control/spool listings.
#[derive(Debug, Clone)]
pub struct MessageMetadata {
    pub status: Option<String>,
    pub domain: Option<String>,
    pub attempts: Option<u32>,
}

/// Trait for the underlying storage mechanism
///
/// This trait defines the core operations for message storage backends.
/// Implementations can store messages in memory, on disk, in databases, etc.
///
/// # Trait Object Safety
/// This trait uses `async_trait` to remain dyn-safe, allowing for
/// `Arc<dyn BackingStore>` trait objects. While this adds a small Box
/// allocation per async call (~10-20ns), this overhead is negligible
/// compared to I/O operations (microseconds to milliseconds).
///
/// # Security
/// Implementations must:
/// - Validate all inputs (especially IDs to prevent path traversal)
/// - Handle concurrent access safely
/// - Prevent data corruption during writes
#[async_trait]
pub trait BackingStore: Send + Sync + std::fmt::Debug {
    /// Write a context to the backing store and return its tracking ID
    ///
    /// The tracking ID is generated by the backing store and is guaranteed to be unique.
    /// The tracking ID will be set in the context's `tracking_id` field.
    ///
    /// # Errors
    /// Returns an error if the context cannot be written
    async fn write(&self, context: &mut Context) -> crate::Result<SpooledMessageId>;

    /// List all message identifiers
    ///
    /// Messages should be returned in sorted order (by creation time, lexicographically)
    ///
    /// # Errors
    /// Returns an error if the backing store cannot be read
    async fn list(&self) -> crate::Result<Vec<SpooledMessageId>>;

    /// List message identifiers using an incremental cursor when supported.
    ///
    /// Default implementation falls back to a full list scan.
    async fn list_delta(
        &self,
        _cursor: &mut SpoolScanCursor,
        _mode: SpoolScanMode,
    ) -> crate::Result<Vec<SpooledMessageId>> {
        self.list().await
    }

    /// Read a specific message and return its full context
    ///
    /// # Errors
    /// Returns an error if the message cannot be found or read
    async fn read(&self, id: &SpooledMessageId) -> crate::Result<Context>;

    /// Read only message metadata without loading the body
    ///
    /// Default implementation falls back to [`read`]. Backends should override
    /// this to avoid loading the message body when only metadata is needed.
    ///
    /// # Errors
    /// Returns an error if the message cannot be found or read
    async fn read_metadata(&self, id: &SpooledMessageId) -> crate::Result<Context> {
        self.read(id).await
    }

    /// Read metadata together with a size hint in a single call when supported.
    ///
    /// Default implementation calls [`read_metadata`] and falls back to
    /// [`message_size`] when the returned context has no body loaded.
    async fn read_metadata_with_size(
        &self,
        id: &SpooledMessageId,
    ) -> crate::Result<(Context, Option<usize>)> {
        let ctx = self.read_metadata(id).await?;
        let size = if let Some(data) = ctx.data.as_ref() {
            Some(data.len())
        } else {
            self.message_size(id).await?
        };
        Ok((ctx, size))
    }

    /// Read only metadata and size without loading the full body.
    ///
    /// Default implementation calls [`read_metadata_with_size`] and extracts
    /// fields; backends can override to avoid deserializing unused fields.
    async fn read_metadata_summary(
        &self,
        id: &SpooledMessageId,
    ) -> crate::Result<(MessageMetadata, Option<usize>)> {
        let (ctx, size) = self.read_metadata_with_size(id).await?;
        let meta = MessageMetadata {
            status: ctx.delivery.as_ref().map(|d| format!("{:?}", d.status)),
            domain: ctx.delivery.as_ref().map(|d| d.domain.to_string()),
            attempts: ctx
                .delivery
                .as_ref()
                .map(|d| u32::try_from(d.attempt_history.len()).unwrap_or_default()),
        };
        Ok((meta, size))
    }

    /// Get the size of the message body in bytes without reading the full data
    ///
    /// Default implementation loads the full message and reports the size of
    /// the in-memory body.
    ///
    /// # Errors
    /// Returns an error if the message cannot be found or read
    async fn message_size(&self, id: &SpooledMessageId) -> crate::Result<Option<usize>> {
        let context = self.read(id).await?;
        Ok(context.data.as_ref().map(|d| d.len()))
    }

    /// Update an existing message in the backing store
    ///
    /// This allows updating the context (especially delivery metadata) without
    /// changing the tracking ID. Used by the delivery processor to persist
    /// delivery state changes.
    ///
    /// # Errors
    /// Returns an error if the message cannot be found or updated
    async fn update(&self, id: &SpooledMessageId, context: &Context) -> crate::Result<()>;

    /// Open a streaming reader for the message body.
    ///
    /// Default implementation loads the message into memory and returns a cursor.
    /// Backends should override this to avoid buffering large messages.
    ///
    /// # Errors
    /// Returns an error if the message cannot be found or read
    async fn open_message_stream(&self, id: &SpooledMessageId) -> crate::Result<MessageStream> {
        let context = self.read(id).await?;
        let data = context.data.unwrap_or_else(|| Arc::from(Vec::<u8>::new()));
        Ok(Box::pin(Cursor::new(data)))
    }

    /// Delete a message
    ///
    /// # Errors
    /// Returns an error if the message cannot be deleted
    async fn delete(&self, id: &SpooledMessageId) -> crate::Result<()>;
}
